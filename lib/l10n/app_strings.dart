  /// All catalogs by language code — exposed so a test can check that every
  /// language defines exactly the keys English does.
  @visibleForTesting
  static Map<String, Map<String, String>> get catalogs =>
      {'en': _en, 'si': _si, 'ta': _ta, 'ar': _ar};

  static AppStrings forCode(String code) => switch (code) {
        'si' => si,
        'ta' => ta,
        'ar' => ar,
        _ => en,
      };

  String t(String key) => _map[key] ?? _en[key] ?? key;

  /// Fills `{name}` placeholders, e.g. `f('sentAt', {'time': '10:42'})`.
  String f(String key, Map<String, Object> values) {
    var out = t(key);
    values.forEach((k, v) => out = out.replaceAll('{$k}', '$v'));
    return out;
  }

  /// Localized incident category name (keys: `cat_<dbValue>`).
  String category(IncidentCategory c) => t('cat_${c.dbValue}');

  /// "5m ago" style relative time for alert lists.
  String timeAgo(DateTime time, {DateTime? now}) {
    final diff = (now ?? DateTime.now()).difference(time);
    if (diff.inMinutes < 1) return t('justNow');
    if (diff.inMinutes < 60) return f('minutesAgo', {'n': diff.inMinutes});
    if (diff.inHours < 24) return f('hoursAgo', {'n': diff.inHours});
    return f('daysAgo', {'n': diff.inDays});
  }

