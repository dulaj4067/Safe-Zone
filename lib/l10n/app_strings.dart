/// The citizen string catalog for the user's chosen language, falling back
/// to English when [AccessibilityProvider] isn't in the tree (e.g. tests).
/// Pass `listen: false` from callbacks (button handlers, snackbars).
AppStrings appStringsOf(BuildContext context, {bool listen = true}) {
  try {
    final a11y = Provider.of<AccessibilityProvider>(context, listen: listen);
    return AppStrings.forCode(a11y.localeCode);
  } catch (_) {
    return AppStrings.en;
  }
}
