  const AdminStrings._(this.localeCode, this._map);

  final String localeCode;
  final Map<String, String> _map;

  static const en = AdminStrings._('en', _en);
  static const si = AdminStrings._('si', _si);
  static const ta = AdminStrings._('ta', _ta);
  static const ar = AdminStrings._('ar', _ar);

  static AdminStrings forCode(String code) {
    return switch (code) {
      'si' => si,
      'ta' => ta,
      'ar' => ar,
      _ => en,
    };
  }

  String t(String key) => _map[key] ?? _en[key] ?? key;

  String channelsActive(int count) {
    return switch (localeCode) {
      'si' => count == 1 ? 'චැනල් 1ක් සක්‍රියයි' : 'චැනල් $countක් සක්‍රියයි',
      'ta' => count == 1 ? '1 சேனல் இயக்கத்தில்' : '$count சேனல்கள் இயக்கத்தில்',
      'ar' => count == 1 ? 'قناة واحدة نشطة' : (count == 2 ? 'قناتان نشطتان' : '$count قنوات نشطة'),
      _ => count == 1 ? '1 channel active' : '$count channels active',
    };
  }

  String stepOf(int current, int total) {
    final template = t('stepOf');
    return template.replaceAll('{current}', '$current').replaceAll('{total}', '$total');
  }

  String feedbackResponses(int count) {
    return switch (localeCode) {
      'si' => count == 1 ? 'ප්‍රතිචාර 1ක්' : 'ප්‍රතිචාර $countක්',
      'ta' => count == 1 ? '1 பதில்' : '$count பதில்கள்',
      'ar' => count == 1 ? 'رد واحد' : '$count ردود',
      _ => count == 1 ? '1 response' : '$count responses',
    };
  }

